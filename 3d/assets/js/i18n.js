export const LANGS = ["ru", "ro", "en"];
const STORE = "aag-lang";
let current = "ru";

export function t(key) {
  return DICT[current][key] ?? DICT.ru[key] ?? key;
}
export function lang() { return current; }

export function detectLang() {
  const q = new URLSearchParams(location.search).get("lang");
  if (q && LANGS.includes(q)) return q;
  try { const s = localStorage.getItem(STORE); if (s && LANGS.includes(s)) return s; } catch (_) {}
  const nav = (navigator.language || "").slice(0, 2).toLowerCase();
  return nav === "ro" ? "ro" : "ru";
}

export function applyLang(next, root = document) {
  if (!LANGS.includes(next)) next = "ru";
  current = next;
  document.documentElement.lang = next;
  try { localStorage.setItem(STORE, next); } catch (_) {}
  root.querySelectorAll("[data-i18n]").forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-attr]").forEach(el => {
    el.dataset.i18nAttr.split(";").forEach(pair => {
      const [attr, key] = pair.split(":");
      if (attr && key) el.setAttribute(attr.trim(), t(key.trim()));
    });
  });
  if (DICT[next]["meta.title"]) document.title = t("meta.title");
  const md = document.querySelector('meta[name="description"]');
  if (md) md.setAttribute("content", t("meta.desc"));
  document.querySelectorAll("[data-lang]").forEach(b => b.setAttribute("aria-pressed", String(b.dataset.lang === next)));
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang: next } }));
}
